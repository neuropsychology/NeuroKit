def _emg_intervalrelated_formatinput(interval, output=None):
    """Format input for dictionary."""
    if output is None:
        output = {}

    # Sanitize input
    colnames = interval.columns.values
    if len([i for i in colnames if "EMG_Onsets" in i]) == 0:
        raise ValueError(
            "NeuroKit error: emg_intervalrelated(): Wrong"
            "input, we couldn't extract activity bursts."
            "Please make sure your DataFrame"
            "contains an `EMG_Onsets` column."
        )

    activity_cols = ["EMG_Amplitude", "EMG_Activity"]
    if not all(col in colnames for col in activity_cols):
        raise ValueError(
            "NeuroKit error: emg_intervalrelated(): Wrong"
            "input, we couldn't extract EMG amplitudes."
            "Please make sure your DataFrame contains both"
            "`EMG_Amplitude` and `EMG_Activity` columns."
        )

    bursts = int(np.sum(interval["EMG_Onsets"] == 1))
    data_bursts = interval.loc[interval["EMG_Activity"] == 1, "EMG_Amplitude"].to_numpy(dtype=float)

    output["EMG_Activation_N"] = bursts
    output["EMG_Amplitude_Mean"] = (
        np.nanmean(data_bursts) if len(data_bursts) > 0 and not np.all(np.isnan(data_bursts)) else np.nan
    )

    return output
